vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require("motion_tools")
local options = { labels = "abc", search = { center = false } }
local caller = vim.deepcopy(options)
plugin.setup(options)
assert(vim.deep_equal(caller, options), "setup mutated caller configuration")
local commands = vim.api.nvim_get_commands({})
local handlers = vim.api.nvim_get_autocmds({})
assert(not pcall(plugin.setup, false), "setup(false) must reject an invalid configuration type")
assert(vim.deep_equal(commands, vim.api.nvim_get_commands({})), "Invalid setup replaced commands")
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({})), "Invalid setup replaced handlers")
plugin.setup(caller)
assert(#vim.api.nvim_get_autocmds({}) == #handlers, "Repeated setup duplicated automatic handlers")
print(
  "motion-tools.nvim: setup input isolation, invalid configuration and registration lifetime passed"
)

local config = require("motion_tools.config")
options.search.center = true
assert(config.options.search.center == false)
local before = vim.deepcopy(config.options)
assert(not pcall(plugin.setup, { labels = "aa" }))
assert(vim.deep_equal(before, config.options))
plugin.dispose()
plugin.dispose()
assert(vim.fn.exists("#MotionToolsSearch") == 0)
assert(vim.deep_equal(config.options, config.defaults))
plugin.setup(caller)
vim.api.nvim_buf_set_lines(0, 0, -1, false, { "one two" })
vim.defer_fn(function()
  plugin.dispose()
end, 10)
assert(plugin.jump({ pattern = "one" }) == false)
assert(not require("motion_tools.session").active)
assert(vim.api.nvim_get_current_line() == "one two")
plugin.setup(caller)
plugin.dispose()
